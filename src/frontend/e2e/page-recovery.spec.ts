import {expect, test} from '@playwright/test'

async function makePage(request: any, title: string, text: string) {
 const response = await request.post('/api/pages', {data: {title, workspace: true, content: JSON.stringify([{type:'paragraph',content:[{type:'text',text}]}])}})
 expect(response.status()).toBe(201)
 return response.json()
}
async function openPage(page: any, title: string) {
 await page.goto('/')
 await page.locator('.home-page-list').getByRole('button', {name: new RegExp(title)}).click()
 await expect(page.locator('.bn-editor')).toBeVisible()
}

test('page history previews, restores, preserves newer writing and rejects a second-window conflict', async ({page, request}) => {
 const p = await makePage(request, 'History original', 'Original writing')
 const changed = await request.put('/api/pages', {data: {...p, title:'History latest', content:JSON.stringify([{type:'paragraph',content:[{type:'text',text:'Newer writing'}]}])}})
 expect(changed.status()).toBe(200)
 await openPage(page, 'History latest')
 await page.getByRole('button',{name:'Page history',exact:true}).click()
 const dialog = page.getByRole('dialog',{name:'Page history',exact:true})
 await dialog.getByRole('button',{name:/History original/}).click()
 await expect(dialog.locator('pre')).toContainText('Original writing')
 const current = await (await request.get(`/api/pages?id=${p.id}`)).json()
 expect((await request.put('/api/pages', {data:{...current,title:'Remote newer',content:JSON.stringify([{type:'paragraph',content:[{type:'text',text:'Remote writing'}]}])}})).status()).toBe(200)
 await dialog.getByRole('button',{name:'Restore this revision'}).click()
 await expect(dialog.getByRole('alert')).toContainText('version conflict')
 expect((await (await request.get(`/api/pages?id=${p.id}`)).json()).content).toContain('Remote writing')
 await dialog.getByRole('button',{name:'Close',exact:true}).click()
 await page.reload()
 await page.locator('.home-page-list').getByRole('button',{name:/Remote newer/}).click()
 await page.getByRole('button',{name:'Page history',exact:true}).click()
 await dialog.getByRole('button',{name:/History original/}).click()
 await dialog.getByRole('button',{name:'Restore this revision'}).click()
 await expect(dialog).toHaveCount(0)
 await expect(page.getByRole('textbox',{name:'Page title'})).toHaveValue('History original')
 await expect(page.locator('.bn-editor')).toContainText('Original writing')
 await page.getByRole('button',{name:'Page history',exact:true}).click()
 await dialog.getByRole('button',{name:/Remote newer/}).click()
 await expect(dialog.locator('pre')).toContainText('Remote writing')
 await dialog.getByRole('button',{name:'Restore this revision'}).click()
 await expect(page.locator('.bn-editor')).toContainText('Remote writing')
})

test('page trash saves local edits, recovers identity and rejects stale pre-delete writes', async ({page, request}) => {
 const original = await makePage(request, 'Recover deleted page', 'Initial content')
 await openPage(page,'Recover deleted page')
 await page.locator('.bn-editor').click()
 await page.keyboard.press('End')
 await page.keyboard.type(' local final edit')
 page.once('dialog',d => d.accept())
 await page.getByRole('button',{name:'Move to trash',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Welcome back'})).toBeVisible()
 expect((await request.get(`/api/pages?id=${original.id}`)).status()).toBe(404)
 await page.reload()
 await page.getByRole('button',{name:'Page trash',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Page trash',exact:true})
 await dialog.locator('.recovery-item').filter({hasText:'Recover deleted page'}).getByRole('button',{name:'Restore page',exact:true}).click()
 await expect(dialog).not.toContainText('Recover deleted page')
 await dialog.getByRole('button',{name:'Close',exact:true}).click()
 await page.locator('.home-page-list').getByRole('button',{name:/Recover deleted page/}).click()
 await expect(page.locator('.bn-editor')).toContainText('local final edit')
 const recovered=await (await request.get(`/api/pages?id=${original.id}`)).json()
 expect(recovered.id).toBe(original.id)
 expect(recovered.version).toBeGreaterThan(original.version)
 expect((await request.put('/api/pages',{data:{...original,content:'stale'}})).status()).toBe(409)
})

test('history loading retry, focus and narrow reduced-motion layout', async ({page,request}) => {
 const p=await makePage(request,'Narrow history','Saved history')
 expect((await request.put('/api/pages',{data:{...p,title:'Narrow changed'}})).status()).toBe(200)
 await page.setViewportSize({width:390,height:844})
 await page.emulateMedia({reducedMotion:'reduce'})
 await openPage(page,'Narrow changed')
 let fail=true
 await page.route('**/api/page-history?*',async route=>{if(fail){fail=false;await route.fulfill({status:500,contentType:'application/json',body:'{"error":"Retry history loading"}'});return};await route.continue()})
 await page.getByRole('button',{name:'Page history',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Page history',exact:true})
 await expect(dialog.getByRole('alert')).toContainText('Retry history loading')
 await dialog.getByRole('button',{name:'Retry loading',exact:true}).click()
 await dialog.getByRole('button',{name:/Narrow history/}).click()
 await expect(dialog.locator('pre')).toContainText('Saved history')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 expect(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true)
 await page.screenshot({path:'test-results/database-evidence/page-history-narrow.png',fullPage:true})
 await page.keyboard.press('Escape')
 await expect(dialog).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Page history',exact:true})).toBeFocused()
 await page.setViewportSize({width:1280,height:900})
 await page.getByRole('button',{name:'Switch to dark theme'}).click()
 await page.getByRole('button',{name:'Page history',exact:true}).click()
 await dialog.getByRole('button',{name:/Narrow history/}).click()
 await expect(dialog.locator('pre')).toContainText('Saved history')
 await page.screenshot({path:'test-results/database-evidence/page-history-desktop-dark.png',fullPage:true})
})
