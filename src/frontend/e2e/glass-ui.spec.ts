import {expect,test} from '@playwright/test'
import fs from 'node:fs/promises'

test.use({trace:'retain-on-failure',screenshot:'only-on-failure'})
async function defaults(request:import('@playwright/test').APIRequestContext){
 const response=await request.get('/api/appearance');expect(response.ok()).toBe(true)
 const current=await response.json()
 const saved=await request.put('/api/appearance',{data:{...current,style:'glass',wallpaper:'sakura',material:'balanced'}})
 expect(saved.ok()).toBe(true)
}
test.beforeEach(async({request,page})=>{
 await defaults(request)
 // CI hosts may request solid materials at OS level. Establish the normal
 // glass condition explicitly; the accessibility test then exercises both overrides.
 const cdp=await page.context().newCDPSession(page)
 await cdp.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-transparency',value:'no-preference'},{name:'prefers-contrast',value:'no-preference'}]})
})
test.afterEach(async({request})=>{await defaults(request)})
async function openAppearance(page:import('@playwright/test').Page){
 await page.getByRole('button',{name:'Appearance',exact:true}).click()
 return page.getByRole('dialog',{name:'Appearance',exact:true})
}
test('glass default, generated wallpaper and portable classic switch persist in a fresh browser context',async({page,browser})=>{
 await page.goto('/')
 await expect(page.locator('html')).toHaveAttribute('data-interface','glass')
 await expect(page.getByText('Welcome back',{exact:true})).toBeVisible()
 expect(await page.locator('.main').evaluate(element=>getComputedStyle(element).backdropFilter)).not.toBe('none')
 expect(await page.locator('.sidebar').evaluate(element=>getComputedStyle(element).backdropFilter)).not.toBe('none')
 const image=await page.request.get('/wallpapers/sakura.webp');expect(image.status()).toBe(200);expect(image.headers()['content-type']).toContain('image/webp')
 const panel=await openAppearance(page)
 await expect(panel.getByRole('button',{name:'Glass interface',exact:true})).toHaveAttribute('aria-pressed','true')
 await panel.getByRole('button',{name:'Mist wallpaper',exact:true}).click()
 await expect(page.locator('html')).toHaveAttribute('data-wallpaper','mist')
 await panel.getByRole('combobox',{name:'Glass clarity',exact:true}).selectOption('frosted')
 await expect(page.locator('html')).toHaveAttribute('data-material','frosted')
 await panel.getByRole('button',{name:'Classic interface',exact:true}).click()
 await expect(page.locator('html')).toHaveAttribute('data-interface','classic')
 await page.setViewportSize({width:390,height:844})
 await expect(page.getByRole('dialog',{name:'Workspace navigation',exact:true})).toHaveCount(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 const context=await browser.newContext()
 try{const next=await context.newPage();await next.goto('/');await expect(next.locator('html')).toHaveAttribute('data-interface','classic');await expect(next.locator('html')).toHaveAttribute('data-wallpaper','mist')}finally{await context.close()}
 await panel.getByRole('button',{name:'Glass interface',exact:true}).click()
 await expect(page.locator('html')).toHaveAttribute('data-interface','glass')
 await page.keyboard.press('Escape')
 await expect(page.getByRole('button',{name:'Appearance',exact:true})).toBeFocused()
})
test('appearance errors preserve previous material and stale windows require explicit reload',async({page})=>{
 await page.goto('/');const panel=await openAppearance(page)
 await page.route('**/api/appearance',route=>route.request().method()==='PUT'?route.fulfill({status:500,contentType:'application/json',body:'{"error":"Synthetic save failure"}'}):route.continue())
 await panel.getByRole('button',{name:'Mist wallpaper',exact:true}).click()
 await expect(panel.getByRole('alert')).toContainText('Synthetic save failure')
 await expect(page.locator('html')).toHaveAttribute('data-wallpaper','sakura')
 await page.unroute('**/api/appearance')
 const current=await(await page.request.get('/api/appearance')).json()
 expect((await page.request.put('/api/appearance',{data:{...current,material:'frosted'}})).ok()).toBe(true)
 await panel.getByRole('button',{name:'Mist wallpaper',exact:true}).click()
 await expect(panel.getByRole('alert')).toContainText('Appearance changed in another window')
 await panel.getByRole('button',{name:'Reload appearance',exact:true}).click()
 await expect(page.locator('html')).toHaveAttribute('data-material','frosted')
 await panel.getByRole('button',{name:'Mist wallpaper',exact:true}).click()
 await expect(page.locator('html')).toHaveAttribute('data-wallpaper','mist')
})
test('glass is keyboard accessible at 390px and system solid-material preferences override clarity',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/')
 const trigger=page.getByRole('button',{name:'Appearance',exact:true});await trigger.focus();await page.keyboard.press('Enter')
 const panel=page.getByRole('dialog',{name:'Appearance',exact:true});await expect(panel).toBeVisible()
 for(let i=0;i<18;i++)await page.keyboard.press('Tab')
 expect(await panel.evaluate(element=>element.contains(document.activeElement))).toBe(true)
 expect(await panel.evaluate(element=>getComputedStyle(element).transform)).toBe('none')
 await panel.getByRole('combobox',{name:'Glass clarity',exact:true}).selectOption('soft')
 await expect(page.locator('html')).toHaveAttribute('data-material','soft')
 await page.keyboard.press('Escape')
 const cdp=await page.context().newCDPSession(page)
 await cdp.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-transparency',value:'reduce'},{name:'prefers-reduced-motion',value:'reduce'}]})
 expect(await page.locator('.main').evaluate(element=>getComputedStyle(element).backdropFilter)).toBe('none')
 expect(await page.locator('.main').evaluate(element=>getComputedStyle(element).backgroundColor)).toBe('rgb(255, 255, 255)')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.getByRole('button',{name:'Toggle sidebar',exact:true}).click()
 const nav=page.getByRole('dialog',{name:'Workspace navigation',exact:true});await expect(nav).toBeVisible()
 expect(await nav.locator('.sidebar').evaluate(element=>getComputedStyle(element).backdropFilter)).toBe('none')
 await page.getByRole('button',{name:'Close navigation',exact:true}).click()
 await expect(nav).toHaveCount(0)
 await cdp.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-contrast',value:'more'}]})
 expect(await page.locator('.main').evaluate(element=>getComputedStyle(element).backgroundColor)).toBe('rgb(255, 255, 255)')
})
