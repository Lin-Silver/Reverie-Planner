import {expect, test} from '@playwright/test'
import {execFileSync} from 'node:child_process'
import fs from 'node:fs/promises'

test.use({trace: 'retain-on-failure', screenshot: 'only-on-failure'})

function zip(files: Record<string,string>): Buffer {
 return execFileSync(process.platform==='win32'?'python':'python3', ['-c', 'import sys,json,io,zipfile; b=io.BytesIO(); z=zipfile.ZipFile(b,"w",zipfile.ZIP_DEFLATED); [z.writestr(k,v) for k,v in json.load(sys.stdin).items()]; z.close(); sys.stdout.buffer.write(b.getvalue())'], {input:JSON.stringify(files)})
}
async function settings(page: import('@playwright/test').Page) {
 await page.goto('/')
 await page.locator('.nav-item').filter({hasText:'Settings'}).click()
 return page.getByRole('region',{name:'Markdown package import'})
}
test('Markdown ZIP previews nested pages, imports formatting and follows internal links while preserving writing', async({page})=>{
 const name='Package '+Date.now()
 const prior=await (await page.request.post('/api/pages',{data:{title:name,content:'Existing writing',workspace:true}})).json()
 const panel=await settings(page)
 const files={[name+'.md']:'# '+name+'\n\nParent text\n\n[Visit child]('+encodeURIComponent(name)+'/Child.md)',[name+'/Child.md']:'# Child\n\nNested offline writing.'}
 await panel.getByLabel('Markdown package ZIP').setInputFiles({name:'notes.zip',mimeType:'application/zip',buffer:zip(files)})
 const before=await (await page.request.get('/api/pages')).json()
 await panel.getByRole('button',{name:'Preview Markdown package',exact:true}).click()
 await expect(panel.getByRole('status')).toContainText('Preview ready')
 await expect(panel.getByLabel('Markdown package contents')).toContainText('2 Markdown pages')
 expect(await (await page.request.get('/api/pages')).json()).toEqual(before)
 await panel.getByRole('button',{name:'Import as new pages',exact:true}).click()
 await expect(panel.getByRole('status')).toContainText('Imported 2 pages')
 const after=await (await page.request.get('/api/pages')).json()
 const parent=after.find((p:{title:string;id:string})=>p.title===name&&p.id!==prior.id)
 const child=after.find((p:{parentId:string})=>p.parentId===parent.id)
 expect(child.title).toBe('Child')
 expect((await (await page.request.get('/api/pages?id='+prior.id)).json()).content).toBe('Existing writing')
 await page.goto('/?page='+parent.id)
 await expect(page.getByLabel('Page title')).toHaveValue(name)
 await expect(page.locator('.bn-editor h1')).toContainText(name)
 const link=page.locator('.bn-editor').getByRole('link',{name:'Visit child',exact:true})
 await expect(link).toHaveAttribute('href','/?page='+child.id)
 await page.locator('.bn-editor').click()
 await page.keyboard.press('End'); await page.keyboard.type(' appended before navigation')
 await link.click()
 await expect(page.getByLabel('Page title')).toHaveValue('Child')
 await expect(page.locator('.bn-editor')).toContainText('Nested offline writing.')
 expect((await (await page.request.get('/api/pages?id='+parent.id)).json()).content).toContain('appended before navigation')
 await page.reload()
 await expect(page.getByLabel('Page title')).toHaveValue('Child')
})

test('Markdown import retry after a lost successful response returns the same pages',async({page})=>{
 const panel=await settings(page)
 await panel.getByLabel('Markdown package ZIP').setInputFiles({name:'retry.zip',mimeType:'application/zip',buffer:zip({'Retry.md':'# Retry\n\nKeep one copy.'})})
 await panel.getByRole('button',{name:'Preview Markdown package',exact:true}).click()
 await expect(panel.getByRole('status')).toContainText('Preview ready')
 const before=(await (await page.request.get('/api/pages')).json()).length
 await page.route('**/api/import/markdown',async route=>{const response=await route.fetch();expect(response.status()).toBe(201);await route.abort('failed')},{times:1})
 await panel.getByRole('button',{name:'Import as new pages',exact:true}).click()
 await expect(panel.getByRole('alert')).toBeVisible()
 expect((await (await page.request.get('/api/pages')).json()).length).toBe(before+2)
 await panel.getByRole('button',{name:'Import as new pages',exact:true}).click()
 await expect(panel.getByRole('status')).toContainText('Imported 1 pages')
 expect((await (await page.request.get('/api/pages')).json()).length).toBe(before+2)
})

test('Markdown package reports unsupported assets and rejects broken links without partial writes',async({page})=>{
 const panel=await settings(page)
 const before=await (await page.request.get('/api/pages')).json()
 await panel.getByLabel('Markdown package ZIP').setInputFiles({name:'assets.zip',mimeType:'application/zip',buffer:zip({'Page.md':'# Text','asset.png':'not an image','Database.csv':'Title\nOne'})})
 await panel.getByRole('button',{name:'Preview Markdown package',exact:true}).click()
 await expect(panel.getByRole('alert')).toContainText('Unsupported file: asset.png')
 await expect(panel.getByRole('alert')).toContainText('Database.csv')
 await expect(panel.getByRole('button',{name:'Import as new pages',exact:true})).toHaveCount(0)
 await panel.getByLabel('Markdown package ZIP').setInputFiles({name:'broken.zip',mimeType:'application/zip',buffer:zip({'Page.md':'[Missing page](missing.md)'})})
 await panel.getByRole('button',{name:'Preview Markdown package',exact:true}).click()
 await expect(panel.getByRole('alert')).toContainText('missing local link target')
 await expect(panel.getByRole('button',{name:'Import as new pages',exact:true})).toBeDisabled()
 expect(await (await page.request.get('/api/pages')).json()).toEqual(before)
 console.log('import-narrow: resizing')
 await page.setViewportSize({width:390,height:844})
 await page.emulateMedia({reducedMotion:'reduce',colorScheme:'light'})
 const navigation=page.getByRole('dialog',{name:'Workspace navigation',exact:true})
 await expect(navigation).toBeVisible()
 await navigation.getByRole('button',{name:'Close navigation',exact:true}).click()
 await expect(navigation).toHaveCount(0)
 console.log('import-narrow: navigation closed')
 console.log('import-narrow: choosing fixed package')
 await panel.getByLabel('Markdown package ZIP').setInputFiles({name:'fixed.zip',mimeType:'application/zip',buffer:zip({'Page.md':'# Fixed\n\nOffline again.'})})
 await panel.getByRole('button',{name:'Preview Markdown package',exact:true}).click()
 await expect(panel.getByRole('status')).toContainText('Preview ready')
 console.log('import-narrow: preview ready')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await fs.mkdir('test-results/import-evidence',{recursive:true})
 console.log('import-narrow: capturing screenshot')
 await page.screenshot({path:'test-results/import-evidence/narrow-preview.png',fullPage:true})
 console.log('import-narrow: screenshot captured')
 await panel.getByRole('button',{name:'Import as new pages',exact:true}).focus()
 await page.keyboard.press('Enter')
 console.log('import-narrow: submitted by keyboard')
 await expect(panel.getByRole('status')).toContainText('Imported 1 pages')
})
