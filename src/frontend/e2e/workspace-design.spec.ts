test('light, dark and reduced transparency surfaces remain usable', async ({page}) => {
  await page.goto('/')
  await expect(page.getByText('Welcome back')).toBeVisible()
  await page.screenshot({path:'test-results/database-evidence/design-home-light.png',fullPage:true})
  await page.getByRole('button', {name:'Switch to dark theme'}).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
  await page.screenshot({path:'test-results/database-evidence/design-home-dark.png',fullPage:true})
  const cdp=await page.context().newCDPSession(page)
  await cdp.send('Emulation.setEmulatedMedia', {features:[{name:'prefers-reduced-transparency',value:'reduce'}]})
  expect(await page.locator('.sidebar').evaluate(el=>getComputedStyle(el).backdropFilter)).toBe('none')
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.getByRole('button', {name:'Quick find',exact:true}).click()
  const dialog=page.getByRole('dialog', {name:'Quick find',exact:true})
  expect(await dialog.evaluate(el=>getComputedStyle(el).transform)).toBe('none')
  await page.keyboard.press('Escape')
  await page.getByRole('button', {name:'Templates',exact:true}).click()
  await page.screenshot({path:'test-results/database-evidence/design-templates-dark.png',fullPage:true})
})


test('page titles update recent cards after save and full-width preference survives reload', async ({page}) => {
  await page.goto('/')
  await page.getByRole('button', {name:'New page',exact:true}).click()
  await expect(page.locator('.bn-editor')).toBeVisible()
  const title='A page with a new title '+Date.now()
  await page.getByLabel('Page title').fill(title)
  await page.getByRole('button', {name:'Full width',exact:true}).click()
  await expect(page.locator('.document-page')).toHaveClass(/full-width/)
  await page.locator('.nav-item').filter({hasText:'Home'}).click()
  await expect(page.locator('.page-card').filter({hasText:title})).toBeVisible()
  await page.reload()
  await page.locator('.page-card').filter({hasText:title}).click()
  await expect(page.locator('.document-page')).toHaveClass(/full-width/)
})

