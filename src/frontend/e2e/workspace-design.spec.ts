import { expect, test } from '@playwright/test'
import fs from 'node:fs/promises'
const API = '/api'

test('templates create editable pages and portable favorites survive a fresh browser context', async ({ page, browser }) => {
  await page.goto('/')
  await page.getByRole('button', {name: 'Templates', exact: true}).click()
  await page.getByRole('button', {name: /Meeting notes Decisions/}).click()
  await expect(page.getByLabel('Page title')).toHaveValue('Meeting notes')
  await expect(page.locator('.bn-editor')).toContainText('Meeting details')
  await page.getByRole('button', {name: 'Add to favorites', exact: true}).click()
  await expect(page.getByRole('button', {name: 'Remove from favorites'})).toBeVisible()
  const library = await (await page.request.get(API + '/page-library')).json()
  expect(library.favorites.length).toBeGreaterThan(0)
  const context = await browser.newContext()
  try {
    const next = await context.newPage()
    await next.goto('/')
    await expect(next.locator('.favorite-link').filter({hasText: 'Meeting notes'})).toBeVisible()
    await expect(next.locator('.page-card').filter({hasText: 'Meeting notes'}).first()).toBeVisible()
    await next.locator('.favorite-link').filter({hasText: 'Meeting notes'}).click()
    await next.getByRole('button', {name: 'Remove from favorites'}).click()
    await expect(next.getByRole('button', {name: 'Add to favorites', exact: true})).toBeVisible()
    await expect(next.locator('.bn-editor')).toContainText('Meeting details')
  } finally { await context.close() }
})

test('Markdown appends, persists and exports current blocks without an AI provider', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', {name: 'New page', exact: true}).click()
  await expect(page.locator('.bn-editor')).toBeVisible()
  await page.getByLabel('Import Markdown file').setInputFiles({name:'notes.md',mimeType:'text/markdown',buffer:Buffer.from('# Imported ideas\n\nKeep this knowledge offline.\n\n- First step')})
  await expect(page.locator('.bn-editor')).toContainText('Imported ideas')
  await expect(page.getByTestId('page-save-status')).toContainText('saved', {timeout: 15000})
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', {name:'Export Markdown',exact:true}).click()])
  const content = await fs.readFile((await download.path())!, 'utf8')
  expect(content).toContain('# Imported ideas')
  expect(content).toContain('Keep this knowledge offline.')
  const [blocks] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', {name:'Export blocks',exact:true}).click()])
  expect(JSON.parse(await fs.readFile((await blocks.path())!, 'utf8')).some((b: {type:string}) => b.type === 'heading')).toBe(true)
  await page.locator('.nav-item').filter({hasText: 'Home'}).click()
  await page.locator('.page-card').filter({hasText: 'Untitled'}).first().click()
  await expect(page.locator('.bn-editor')).toContainText('Keep this knowledge offline.')
})

test('template creation reports errors and permits a deliberate retry', async ({page}) => {
  await page.goto('/')
  await page.getByRole('button', {name:'Templates',exact:true}).click()
  await page.route('**/api/pages', route => route.request().method() === 'POST' ? route.fulfill({status:500,contentType:'application/json',body:'{"error":"Template could not be saved"}'}) : route.continue())
  await page.getByRole('button', {name:/Project brief Turn/}).click()
  await expect(page.getByRole('alert')).toContainText('Template could not be saved')
  await page.unroute('**/api/pages')
  await page.getByRole('button', {name:/Project brief Turn/}).click()
  await expect(page.getByLabel('Page title')).toHaveValue('Project brief')
  await expect(page.locator('.bn-editor')).toContainText('Success looks like')
})

test('native command dialog contains focus and restores its trigger without motion', async ({page}) => {
  await page.goto('/')
  const trigger = page.getByRole('button', {name:'Quick find',exact:true})
  await trigger.focus()
  await trigger.press('Enter')
  const dialog = page.getByRole('dialog', {name:'Quick find',exact:true})
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('input')).toBeFocused()
  for(let i=0;i<25;i++) await page.keyboard.press('Tab')
  expect(await dialog.evaluate(el=>el.contains(document.activeElement))).toBe(true)
  expect(await dialog.evaluate(el=>getComputedStyle(el).transitionDuration)).toBe('0s')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
})

